-- 1. DDL: TABLE CREATION

CREATE TABLE departments (
    dept_id NUMBER PRIMARY KEY,
    dept_name VARCHAR2(50) NOT NULL UNIQUE
);

CREATE TABLE employees (
    emp_id NUMBER PRIMARY KEY,
    emp_name VARCHAR2(100) NOT NULL,
    salary NUMBER(10,2),
    hire_date DATE DEFAULT SYSDATE,
    dept_id NUMBER,
    FOREIGN KEY (dept_id) REFERENCES departments(dept_id)
);

CREATE TABLE students (
    student_id NUMBER PRIMARY KEY,
    student_name VARCHAR2(100) NOT NULL,
    enrollment_year NUMBER(4),
    major_dept_id NUMBER,
    FOREIGN KEY (major_dept_id) REFERENCES departments(dept_id)
);

CREATE TABLE courses (
    course_id NUMBER PRIMARY KEY,
    title VARCHAR2(100) NOT NULL,
    credits NUMBER CHECK (credits IN (1, 2, 3, 4)),
    dept_id NUMBER,
    FOREIGN KEY (dept_id) REFERENCES departments(dept_id)
);

CREATE TABLE enrollments (
    enroll_id NUMBER PRIMARY KEY,
    student_id NUMBER NOT NULL,
    course_id NUMBER NOT NULL,
    grade VARCHAR2(2) CHECK (grade IN ('A', 'B', 'C', 'D', 'F', 'W')),
    FOREIGN KEY (student_id) REFERENCES students(student_id),
    FOREIGN KEY (course_id) REFERENCES courses(course_id)
);

CREATE TABLE payments (
    payment_id NUMBER PRIMARY KEY,
    student_id NUMBER NOT NULL,
    amount NUMBER(8,2) CHECK (amount > 0),
    FOREIGN KEY (student_id) REFERENCES students(student_id)
);

